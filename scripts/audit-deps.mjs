#!/usr/bin/env node
// Checks every direct dependency on npm: that the exact name exists, how
// many weekly downloads it has, who maintains it, when it was last
// published, and whether the installed version is deprecated. Flags
// anything that looks abandoned, little used, or deprecated. Writes
// docs/dependency-audit.md; exits 1 when something needs a look.
//
//   node scripts/audit-deps.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const names = [...Object.keys(pkg.dependencies ?? {}), ...Object.keys(pkg.devDependencies ?? {})].sort();

const TWO_YEARS = 2 * 365 * 24 * 60 * 60 * 1000;
const LOW_DOWNLOADS = 10_000;

/** GETs JSON, waiting and retrying when npm says too many requests. */
async function json(url) {
  for (let attempt = 0; attempt < 5; attempt++) {
    const response = await fetch(url);
    if (response.status === 429) {
      await new Promise((resolve) => setTimeout(resolve, 2000 * 2 ** attempt));
      continue;
    }
    return response.ok ? response.json() : null;
  }
  throw new Error(`npm kept refusing ${url}`);
}

function installedVersion(name) {
  try {
    return require(`${name}/package.json`).version;
  } catch {
    return null;
  }
}

const rows = [];
for (const name of names) {
  const meta = await json(`https://registry.npmjs.org/${name.replace('/', '%2f')}`);
  const downloads = (await json(`https://api.npmjs.org/downloads/point/last-week/${name}`))?.downloads ?? 0;
  const installed = installedVersion(name);
  if (!meta) {
    rows.push({ name, flags: ['NOT ON NPM'], downloads, installed });
    continue;
  }
  const latest = meta['dist-tags']?.latest;
  const published = new Date(meta.time?.[latest] ?? meta.time?.modified ?? 0);
  const deprecated = installed ? meta.versions?.[installed]?.deprecated : undefined;
  const flags = [];
  if (Date.now() - published.getTime() > TWO_YEARS) flags.push('no release in 2 years');
  if (downloads < LOW_DOWNLOADS) flags.push('few downloads');
  if (deprecated) flags.push(`deprecated: ${deprecated}`);
  if (!(meta.maintainers ?? []).length) flags.push('no maintainers');
  rows.push({
    name,
    installed,
    latest,
    published: published.toISOString().slice(0, 10),
    downloads,
    maintainers: (meta.maintainers ?? [])
      .map((m) => m.name)
      .slice(0, 3)
      .join(', '),
    flags,
  });
}

const flagged = rows.filter((row) => row.flags.length);
const lines = [
  '# Dependency audit',
  '',
  `Generated by \`node scripts/audit-deps.mjs\` on ${new Date().toISOString().slice(0, 10)}: every direct`,
  'dependency, checked on npm by its exact name. Flags: no release in two years, under',
  `${LOW_DOWNLOADS.toLocaleString('en')} downloads a week, the installed version deprecated, no maintainers.`,
  '',
  `${rows.length} packages, ${flagged.length} flagged.`,
  '',
  '| Package | Installed | Latest | Last release | Weekly downloads | Maintainers | Flags |',
  '|---|---|---|---|---:|---|---|',
  ...rows.map(
    (row) =>
      `| \`${row.name}\` | ${row.installed ?? '-'} | ${row.latest ?? '-'} | ${row.published ?? '-'} | ${row.downloads.toLocaleString('en')} | ${row.maintainers ?? '-'} | ${row.flags.join('; ') || 'none'} |`,
  ),
  '',
];
await writeFile(new URL('../docs/dependency-audit.md', import.meta.url), lines.join('\n'));
console.log(`${rows.length} packages, ${flagged.length} flagged`);
for (const row of flagged) console.log(`  ${row.name}: ${row.flags.join('; ')}`);
process.exitCode = flagged.length ? 1 : 0;
