#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md: every open-source package the app ships
 * with (npm's production dependency tree), its licence and copyright holder,
 * plus the fonts, icons and data used, and each licence's full text once.
 *
 * Run `npm run licenses` after adding, removing or updating dependencies.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT = join(ROOT, 'THIRD_PARTY_NOTICES.md');

/** npm exits non-zero over unmet optional peers, but still prints the tree. */
function productionTree() {
  const args = ['ls', '--omit=dev', '--all', '--long', '--json'];
  const options = { cwd: ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, shell: process.platform === 'win32' };
  try {
    return JSON.parse(execFileSync('npm', args, options));
  } catch (error) {
    if (error.stdout) return JSON.parse(error.stdout);
    throw error;
  }
}

function licenseFile(dir) {
  const name = readdirSync(dir).find((file) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(file));
  return name ? readFileSync(join(dir, name), 'utf8') : null;
}

function repositoryOf(pkg) {
  const url = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  if (!url) return null;
  return url
    .replace(/^git\+/, '')
    .replace(/^git:\/\//, 'https://')
    .replace(/^github:/, 'https://github.com/')
    .replace(/^(?!https?:)([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1')
    .replace(/\.git$/, '');
}

/** The licence file's copyright line, else the author, else where the source lives. */
function copyrightOf(pkg, text) {
  const lines = (text ?? '')
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^(copyright|\(c\)|©)/i.test(line))
    .slice(0, 2);
  if (lines.length) return lines.join('; ');
  const author = typeof pkg.author === 'string' ? pkg.author : pkg.author?.name;
  if (author) return author;
  const repository = repositoryOf(pkg);
  return repository ? `See ${repository}` : '—';
}

function licenseId(pkg, fromTree) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((entry) => entry.type ?? entry).join(' OR ');
  return fromTree ?? 'See package';
}

const packages = new Map();
(function walk(dependencies) {
  for (const [name, node] of Object.entries(dependencies ?? {})) {
    if (!node.version || !node.path || !existsSync(join(node.path, 'package.json'))) continue;
    const key = `${name}@${node.version}`;
    if (!packages.has(key)) {
      const pkg = JSON.parse(readFileSync(join(node.path, 'package.json'), 'utf8'));
      const text = licenseFile(node.path);
      packages.set(key, {
        name,
        version: node.version,
        license: licenseId(pkg, node.license),
        copyright: copyrightOf(pkg, text),
        text,
      });
    }
    walk(node.dependencies);
  }
})(productionTree().dependencies);

const sorted = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\s+/g, ' ');

// One full text per licence: the first package whose licence is exactly it.
const atomicIds = [...new Set(sorted.flatMap((p) => p.license.split(/\s+(?:AND|OR)\s+|[()]/).map((id) => id.trim()).filter(Boolean)))];
const texts = atomicIds
  .filter((id) => id !== 'OFL-1.1') // the fonts' own text is added below
  .map((id) => [id, sorted.find((p) => p.license === id && p.text)?.text])
  .filter(([, text]) => text);

const fontLicense = (pkg) => readFileSync(join(ROOT, 'node_modules/@expo-google-fonts', pkg, 'LICENSE_FONT'), 'utf8');
const ofl = fontLicense('barlow-condensed');
const fontCopyright = (pkg) => fontLicense(pkg).split('\n')[0].replace(/,\s*$/, '');

const out = `# Third-party notices

Mongmo is proprietary software (see [LICENSE](LICENSE)). It is built with the
open-source software, fonts and data below, each used under its own licence.

This file is generated by \`npm run licenses\` from the app's production
dependencies (\`npm ls --omit=dev\`). Some of them are build tools that never
end up inside the app; they are listed anyway. Don't edit this file by hand.

## Fonts

Both are used under the SIL Open Font License 1.1 (full text below).

- **Barlow Condensed:** ${fontCopyright('barlow-condensed')}
- **Be Vietnam Pro:** ${fontCopyright('be-vietnam-pro')}

## Icons, maps and data

- **Icons on Android and web:** Lucide (lucide-react-native, ISC licence; listed below).
- **Icons on iOS:** SF Symbols, provided by Apple and used only on Apple platforms, under Apple's terms.
- **Maps:** Apple Maps on iOS and Google Maps on Android, through react-native-maps. Each map shows its provider's attribution.
- **Address suggestions:** Photon (photon.komoot.io), using OpenStreetMap data, © OpenStreetMap contributors, under the Open Database License (ODbL). The app credits OpenStreetMap wherever suggestions are shown.
- **Demo pop-up photos** in \`supabase/seed.sql\`: Unsplash, under the Unsplash License.

## Expo project template

This project started from Expo's \`create-expo-app\` template.
Copyright (c) 2015-present 650 Industries, Inc. (aka Expo). MIT licence (full text below).

## npm packages (${sorted.length})

| Package | Version | Licence | Copyright |
| --- | --- | --- | --- |
${sorted.map((p) => `| ${cell(p.name)} | ${cell(p.version)} | ${cell(p.license)} | ${cell(p.copyright)} |`).join('\n')}

## Licence texts

Each licence's text appears once. The copyright line differs per package (see the
table above); the terms are the same.

${texts.map(([id, text]) => `### ${id}\n\n\`\`\`text\n${text.trim()}\n\`\`\``).join('\n\n')}

### OFL-1.1 (SIL Open Font License 1.1)

\`\`\`text
${ofl.trim()}
\`\`\`
`;

writeFileSync(OUTPUT, out);
console.log(`Wrote ${OUTPUT}: ${sorted.length} packages, ${texts.length + 1} licence texts.`);
